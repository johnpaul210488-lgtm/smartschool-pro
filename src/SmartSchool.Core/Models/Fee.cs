using SmartSchool.Shared.Enums;

namespace SmartSchool.Core.Models;

public sealed class Fee
{
    public int Id { get; set; }

    public int StudentId { get; set; }
    public Student Student { get; set; } = null!;

    public decimal Amount { get; set; }

    // CHANGED: recurring plan charges keep a per-head snapshot and stable period key.
    public int? FeeHeadId { get; set; }
    public FeeHead? FeeHead { get; set; }
    public string? FeeHeadNameSnapshot { get; set; }
    public FeeBillingCycle? BillingCycle { get; set; }
    public string? BillingPeriodKey { get; set; }
    public bool IsAutoGenerated { get; set; }
    public decimal AmountPaid { get; set; }
    public ICollection<FeePayment> Payments { get; set; } = new List<FeePayment>();

    /// <summary>Billing month as "yyyy-MM", e.g. "2026-10".</summary>
    public string Month { get; set; } = string.Empty;

    public DateOnly DueDate { get; set; }

    public DateOnly? PaidDate { get; set; }

    public FeeStatus Status { get; set; } = FeeStatus.Pending;

    /// <summary>Generated on payment: INV-{yyyyMM}-{feeId:D6}.</summary>
    public string? ReceiptNo { get; set; }

    public string? Notes { get; set; }

    public DateTime CreatedAtUtc { get; set; } = DateTime.UtcNow;
}
