/// <summary>
/// Simple fee screen backend:
///  - POST api/FeeCharges            → add selected fees to a class or one student's balance (manual, no plan needed)
///  - GET  api/FeeCharges/student/{id}/history → full fee + payment history of one student
/// </summary>
[ApiController]
[Route("api/[controller]")]
public sealed class FeeChargesController : BaseApiController
{
    private readonly SchoolDbContext _db;

    public FeeChargesController(SchoolDbContext db) => _db = db;

    [HttpPost]
    [Authorize(Roles = AppRoles.Staff)]
    public async Task<ActionResult<ApiResponse<FeeChargeResult>>> Charge(FeeChargeRequest request, CancellationToken ct)
    {
        if (!Enum.TryParse<FeeBillingCycle>(request.Cycle, true, out var cycle))
            return BadRequestEnvelope("Cycle must be Monthly, Quarterly, Annually or OneTime.");
        if (cycle == FeeBillingCycle.PerTerm) cycle = FeeBillingCycle.Quarterly; // legacy value

        if (!DateOnly.TryParseExact(request.PeriodMonth + "-01", "yyyy-MM-dd", out var periodStart))
            return BadRequestEnvelope("PeriodMonth must look like 2026-10.");
        if (request.DueDate == default)
            return BadRequestEnvelope("Due date is required.");

        var lines = request.Items.Where(i => i.Amount > 0m).ToList();
        if (lines.Count == 0)
            return BadRequestEnvelope("Select at least one fee and enter an amount greater than zero.");
        if (lines.Any(i => i.Amount > 10_000_000m))
            return BadRequestEnvelope("Amount must not exceed 10,000,000.");
        if (lines.GroupBy(i => i.FeeHeadId).Any(g => g.Count() > 1))
            return BadRequestEnvelope("Each fee can be selected only once.");

        var isClass = string.Equals(request.Scope, "Class", StringComparison.OrdinalIgnoreCase);
        List<Student> students;
        if (isClass)
        {
            if (request.ClassId is null) return BadRequestEnvelope("Select a class.");
            students = await _db.Students.Where(s => s.ClassId == request.ClassId && s.IsActive).ToListAsync(ct);
        }
        else
        {
            if (request.StudentId is null) return BadRequestEnvelope("Select a student.");
            students = await _db.Students.Where(s => s.Id == request.StudentId && s.IsActive).ToListAsync(ct);
        }
        if (students.Count == 0)
            return NotFoundEnvelope("No active student found for this selection.");

        var headIds = lines.Select(l => l.FeeHeadId).ToList();
        var heads = await _db.FeeHeads.AsNoTracking().Where(h => headIds.Contains(h.Id)).ToDictionaryAsync(h => h.Id, ct);
        if (heads.Count != headIds.Count)
            return BadRequestEnvelope("One or more selected fee heads do not exist.");

        // Same key format the automatic plan worker uses, so both never bill the same period twice.
        var periodKey = cycle == FeeBillingCycle.OneTime ? "ONETIME" : $"{cycle}:{periodStart:yyyy-MM}";
        var studentIds = students.Select(s => s.Id).ToList();
        var existing = await _db.Fees.AsNoTracking()
            .Where(f => studentIds.Contains(f.StudentId) && f.BillingPeriodKey == periodKey && f.FeeHeadId != null)
            .Select(f => new { f.StudentId, FeeHeadId = f.FeeHeadId!.Value })
            .ToListAsync(ct);
        var existingSet = existing.Select(x => (x.StudentId, x.FeeHeadId)).ToHashSet();

        int created = 0, skipped = 0;
        foreach (var student in students)
        {
            foreach (var line in lines)
            {
                if (existingSet.Contains((student.Id, line.FeeHeadId))) { skipped++; continue; }

                _db.Fees.Add(new Fee
                {
                    StudentId = student.Id,
                    FeeHeadId = line.FeeHeadId,
                    FeeHeadNameSnapshot = heads[line.FeeHeadId].Name,
                    BillingCycle = cycle,
                    BillingPeriodKey = periodKey,
                    IsAutoGenerated = false,
                    Amount = line.Amount,
                    AmountPaid = 0m,
                    Month = periodStart.ToString("yyyy-MM"),
                    DueDate = request.DueDate,
                    Notes = "Added from the Fee screen.",
                    Status = FeeStatus.Pending,
                    CreatedAtUtc = DateTime.UtcNow
                });
                created++;
            }
        }

        try
        {
            await _db.SaveChangesAsync(ct);
        }
        catch (DbUpdateException)
        {
            // Unique index (student, fee head, period) — another user added the same fee at the same moment.
            return ConflictEnvelope("Some fees were added by someone else at the same time. Check the history and try again.");
        }

        return OkEnvelope(new FeeChargeResult(students.Count, created, skipped),
            $"{created} fee line(s) added for {students.Count} student(s); {skipped} already existed and were skipped.");
    }

    [HttpGet("student/{studentId:int}/history")]
    [Authorize(Roles = AppRoles.Staff)]
    public async Task<ActionResult<ApiResponse<StudentFeeHistoryDto>>> History(int studentId, CancellationToken ct)
    {
        var student = await _db.Students.AsNoTracking().Include(s => s.Class)
            .FirstOrDefaultAsync(s => s.Id == studentId, ct);
        if (student is null)
            return NotFoundEnvelope($"Student {studentId} was not found.");

        var fees = await _db.Fees.AsNoTracking()
            .Where(f => f.StudentId == studentId)
            .OrderBy(f => f.Month).ThenBy(f => f.Id)
            .ToListAsync(ct);
        var feeIds = fees.Select(f => f.Id).ToList();
        var payments = await _db.FeePayments.AsNoTracking()
            .Where(p => feeIds.Contains(p.FeeId))
            .OrderBy(p => p.CreatedAtUtc).ThenBy(p => p.Id)
            .ToListAsync(ct);

        var today = PkTime.TodayPk;
        var feeById = fees.ToDictionary(f => f.Id);

        var rows = fees.Select(f => new FeeHistoryRow(
            f.Id,
            f.Month,
            f.FeeHeadNameSnapshot ?? "Fee",
            f.BillingCycle?.ToString() ?? "Monthly",
            f.DueDate,
            f.Amount,
            f.AmountPaid,
            Math.Max(0m, f.Amount - f.AmountPaid),
            f.Status == FeeStatus.Pending && f.DueDate < today ? "Overdue" : f.Status.ToString(),
            f.ReceiptNo)).ToList();

        var payRows = payments.Select(p =>
        {
            var fee = feeById.TryGetValue(p.FeeId, out var f) ? f : null;
            return new FeeHistoryPayment(
                p.Id,
                p.FeeId,
                fee?.FeeHeadNameSnapshot ?? "Fee",
                fee?.Month ?? string.Empty,
                PkTime.ToPk(p.CreatedAtUtc),
                p.Amount,
                p.ReceiptNo,
                p.Method,
                p.Notes);
        }).ToList();

        var totalAmount = fees.Sum(f => f.Amount);
        var totalPaid = fees.Sum(f => f.AmountPaid);

        var dto = new StudentFeeHistoryDto(
            student.Id,
            student.FullName,
            student.Class.Name + "-" + student.Class.Section,
            student.RollNo,
            student.FatherName,
            student.FatherPhone,
            totalAmount,
            totalPaid,
            Math.Max(0m, totalAmount - totalPaid),
            rows,
            payRows);

        return OkEnvelope(dto);
    }

    /// <summary>
    /// Collect a payment from a student. The amount is spread over their open bills,
    /// oldest due date first; one immutable payment row is written per bill touched.
    /// </summary>
    [HttpPost("student/{studentId:int}/collect")]
    [Authorize(Roles = AppRoles.Staff)]
    public async Task<ActionResult<ApiResponse<FeeCollectResult>>> Collect(
        int studentId, CollectStudentFeeRequest? request, CancellationToken ct)
    {
        if (request is null || request.Amount <= 0m)
            return BadRequestEnvelope("Amount must be greater than zero.");
        if (request.Amount > 10_000_000m)
            return BadRequestEnvelope("Amount must not exceed 10,000,000.");

        var paidDate = request.PaidDate ?? PkTime.TodayPk;
        if (paidDate > PkTime.TodayPk)
            return BadRequestEnvelope("Paid date cannot be in the future.");

        var method = string.IsNullOrWhiteSpace(request.Method) ? "Cash" : request.Method.Trim();
        if (method.Length > 30) return BadRequestEnvelope("Method must be 30 characters or fewer.");
        var notes = string.IsNullOrWhiteSpace(request.Notes) ? null : request.Notes.Trim();
        if (notes is not null && notes.Length > 300) return BadRequestEnvelope("Notes must be 300 characters or fewer.");

        var strategy = _db.Database.CreateExecutionStrategy();
        return await strategy.ExecuteAsync<ActionResult<ApiResponse<FeeCollectResult>>>(async () =>
        {
            await using var tx = await _db.Database.BeginTransactionAsync(System.Data.IsolationLevel.Serializable, ct);

            if (!await _db.Students.AnyAsync(s => s.Id == studentId, ct))
                return NotFoundEnvelope($"Student {studentId} was not found.");

            var bills = await _db.Fees
                .Where(f => f.StudentId == studentId && f.AmountPaid < f.Amount)
                .OrderBy(f => f.DueDate).ThenBy(f => f.Id)
                .ToListAsync(ct);

            var balance = bills.Sum(f => f.Amount - f.AmountPaid);
            if (balance <= 0m)
                return ConflictEnvelope("This student has no balance to collect.");
            if (request.Amount > balance)
                return BadRequestEnvelope($"Amount cannot exceed the balance Rs {balance:N2}.");

            var remaining = request.Amount;
            var touched = 0;
            foreach (var fee in bills)
            {
                if (remaining <= 0m) break;
                var pay = Math.Min(fee.Amount - fee.AmountPaid, remaining);

                var receipt = NewReceiptNo("PAY", fee.Id);
                _db.FeePayments.Add(new FeePayment
                {
                    FeeId = fee.Id,
                    Amount = pay,
                    PaidDate = paidDate,
                    ReceiptNo = receipt,
                    Method = method,
                    Notes = notes,
                    CreatedAtUtc = DateTime.UtcNow
                });
                fee.AmountPaid += pay;
                fee.ReceiptNo = receipt;
                ApplyStatus(fee, paidDate);

                remaining -= pay;
                touched++;
            }

            await _db.SaveChangesAsync(ct);
            await tx.CommitAsync(ct);

            var left = balance - request.Amount;
            return OkEnvelope(new FeeCollectResult(request.Amount, left, touched),
                $"Rs {request.Amount:N2} collected. Remaining balance Rs {left:N2}.");
        });
    }

    /// <summary>
    /// Reverse a wrongly entered payment. Nothing is deleted: a negative "Reversal" row is
    /// added to the ledger and the bill balance is restored. A payment can be reversed once.
    /// </summary>
    [HttpPost("payments/{paymentId:int}/reverse")]
    [Authorize(Roles = AppRoles.Staff)]
    public async Task<ActionResult<ApiResponse<FeeCollectResult>>> ReversePayment(
        int paymentId, ReversePaymentRequest? request, CancellationToken ct)
    {
        var reason = request?.Reason?.Trim() ?? string.Empty;
        if (reason.Length < 3) return BadRequestEnvelope("Reversal ki wajah likhein (kam az kam 3 huruf).");
        if (reason.Length > 200) return BadRequestEnvelope("Reason must be 200 characters or fewer.");

        var strategy = _db.Database.CreateExecutionStrategy();
        return await strategy.ExecuteAsync<ActionResult<ApiResponse<FeeCollectResult>>>(async () =>
        {
            await using var tx = await _db.Database.BeginTransactionAsync(System.Data.IsolationLevel.Serializable, ct);

            var payment = await _db.FeePayments.FirstOrDefaultAsync(p => p.Id == paymentId, ct);
            if (payment is null)
                return NotFoundEnvelope($"Payment {paymentId} was not found.");
            if (payment.Amount <= 0m)
                return ConflictEnvelope("Yeh ek reversal entry hai; ise reverse nahi kiya ja sakta.");

            var marker = $"[REV#{payment.Id}]";
            if (await _db.FeePayments.AnyAsync(p => p.Notes != null && p.Notes.StartsWith(marker), ct))
                return ConflictEnvelope("Yeh payment pehle hi reverse ho chuki hai.");

            var fee = await _db.Fees.FirstOrDefaultAsync(f => f.Id == payment.FeeId, ct);
            if (fee is null)
                return NotFoundEnvelope($"Fee {payment.FeeId} was not found.");

            // Receipt that the bill should point to after the reversal (latest surviving payment).
            var lastReceipt = await _db.FeePayments
                .Where(p => p.FeeId == fee.Id && p.Amount > 0m && p.Id != payment.Id)
                .OrderByDescending(p => p.CreatedAtUtc).ThenByDescending(p => p.Id)
                .Select(p => p.ReceiptNo)
                .FirstOrDefaultAsync(ct);

            var noteText = $"{marker} {reason}";
            _db.FeePayments.Add(new FeePayment
            {
                FeeId = fee.Id,
                Amount = -payment.Amount,
                PaidDate = PkTime.TodayPk,
                ReceiptNo = NewReceiptNo("REV", fee.Id),
                Method = "Reversal",
                Notes = noteText.Length > 300 ? noteText[..300] : noteText,
                CreatedAtUtc = DateTime.UtcNow
            });

            fee.AmountPaid = Math.Max(0m, fee.AmountPaid - payment.Amount);
            fee.ReceiptNo = lastReceipt;
            ApplyStatus(fee, PkTime.TodayPk);

            await _db.SaveChangesAsync(ct);
            await tx.CommitAsync(ct);

            var left = Math.Max(0m, fee.Amount - fee.AmountPaid);
            return OkEnvelope(new FeeCollectResult(-payment.Amount, left, 1),
                $"Rs {payment.Amount:N2} payment reverse ho gayi. Is bill ka baaqi balance Rs {left:N2}.");
        });
    }

    private static string NewReceiptNo(string prefix, int feeId)
        => $"{prefix}-{feeId:D6}-{Guid.NewGuid():N}"[..23].ToUpperInvariant();

    /// <summary>Recomputes status from the paid amount. Same rules as the Pay endpoint.</summary>
    private static void ApplyStatus(Fee fee, DateOnly paidDate)
    {
        if (fee.Amount > 0m && fee.AmountPaid >= fee.Amount)
        {
            fee.Status = FeeStatus.Paid;
            fee.PaidDate = paidDate;
        }
        else
        {
            fee.Status = fee.AmountPaid > 0m ? FeeStatus.Partial : FeeStatus.Pending;
            fee.PaidDate = null;
        }
    }

    /// <summary>
    /// Fee dashboard: one row per student with the sum of all fee heads, what is paid, and the balance.
    /// onlyDue = true returns only students who still owe money.
    /// </summary>
    [HttpGet("students")]
    [Authorize(Roles = AppRoles.Staff)]
    public async Task<ActionResult<ApiResponse<IReadOnlyList<StudentFeeSummaryRow>>>> StudentSummaries(
        [FromQuery] string? search, [FromQuery] int? classId, [FromQuery] bool onlyDue = true,
        CancellationToken ct = default)
    {
        var today = PkTime.TodayPk;
        var query = _db.Students.AsNoTracking().Where(s => s.IsActive);
        if (classId is not null)
            query = query.Where(s => s.ClassId == classId);
        if (!string.IsNullOrWhiteSpace(search))
        {
            var pattern = $"%{search.Trim()}%";
            query = query.Where(s =>
                EF.Functions.Like(s.FullName, pattern) ||
                EF.Functions.Like(s.RollNo, pattern) ||
                EF.Functions.Like(s.FatherName, pattern) ||
                EF.Functions.Like(s.FatherPhone, pattern));
        }
        if (onlyDue)
            query = query.Where(s => _db.Fees.Any(f => f.StudentId == s.Id && f.AmountPaid < f.Amount));

        var rows = await query
            .OrderBy(s => s.Class.Name).ThenBy(s => s.Class.Section).ThenBy(s => s.FullName)
            .Take(500)
            .Select(s => new
            {
                s.Id,
                s.FullName,
                s.RollNo,
                ClassName = s.Class.Name + "-" + s.Class.Section,
                s.FatherName,
                s.FatherPhone,
                Total = _db.Fees.Where(f => f.StudentId == s.Id).Sum(f => (decimal?)f.Amount) ?? 0m,
                Paid = _db.Fees.Where(f => f.StudentId == s.Id).Sum(f => (decimal?)f.AmountPaid) ?? 0m,
                Overdue = _db.Fees.Any(f => f.StudentId == s.Id && f.AmountPaid < f.Amount && f.DueDate < today)
            })
            .ToListAsync(ct);

        var result = rows.Select(x => new StudentFeeSummaryRow(
            x.Id, x.FullName, x.RollNo, x.ClassName, x.FatherName, x.FatherPhone,
            x.Total, x.Paid, Math.Max(0m, x.Total - x.Paid), x.Overdue)).ToList();
        return OkEnvelope<IReadOnlyList<StudentFeeSummaryRow>>(result);
    }

    /// <summary>
    /// Pay selected fee heads of one student in one transaction. Each line is one bill; the amount
    /// may be partial and never exceeds that bill's balance. Unpaid balance stays on the bills.
    /// </summary>
    [HttpPost("student/{studentId:int}/pay-selected")]
    [Authorize(Roles = AppRoles.Staff)]
    public async Task<ActionResult<ApiResponse<FeeCollectResult>>> PaySelected(
        int studentId, PaySelectedRequest? request, CancellationToken ct)
    {
        var lines = request?.Lines ?? new List<PaySelectedLine>();
        if (lines.Count == 0)
            return BadRequestEnvelope("Kam az kam ek fee select karein.");
        if (lines.Any(l => l.Amount <= 0m))
            return BadRequestEnvelope("Har selected fee ka amount zero se zyada hona chahiye.");
        if (lines.Any(l => l.Amount > 10_000_000m))
            return BadRequestEnvelope("Amount must not exceed 10,000,000.");
        if (lines.GroupBy(l => l.FeeId).Any(g => g.Count() > 1))
            return BadRequestEnvelope("Ek fee do dafa select nahi ho sakti.");

        var paidDate = request?.PaidDate ?? PkTime.TodayPk;
        if (paidDate > PkTime.TodayPk)
            return BadRequestEnvelope("Paid date cannot be in the future.");
        var method = string.IsNullOrWhiteSpace(request?.Method) ? "Cash" : request!.Method!.Trim();
        if (method.Length > 30) return BadRequestEnvelope("Method must be 30 characters or fewer.");
        var notes = string.IsNullOrWhiteSpace(request?.Notes) ? null : request!.Notes!.Trim();
        if (notes is not null && notes.Length > 300) return BadRequestEnvelope("Notes must be 300 characters or fewer.");

        var strategy = _db.Database.CreateExecutionStrategy();
        return await strategy.ExecuteAsync<ActionResult<ApiResponse<FeeCollectResult>>>(async () =>
        {
            await using var tx = await _db.Database.BeginTransactionAsync(System.Data.IsolationLevel.Serializable, ct);

            if (!await _db.Students.AnyAsync(s => s.Id == studentId, ct))
                return NotFoundEnvelope($"Student {studentId} was not found.");

            var balanceBefore = await _db.Fees.Where(f => f.StudentId == studentId)
                .SumAsync(f => f.Amount - f.AmountPaid, ct);

            var ids = lines.Select(l => l.FeeId).ToList();
            var fees = await _db.Fees.Where(f => f.StudentId == studentId && ids.Contains(f.Id)).ToListAsync(ct);
            if (fees.Count != ids.Count)
                return BadRequestEnvelope("Kuch selected fees is student ki nahi hain ya mojood nahi.");
            var byId = fees.ToDictionary(f => f.Id);

            foreach (var line in lines)
            {
                var fee = byId[line.FeeId];
                var due = fee.Amount - fee.AmountPaid;
                var name = fee.FeeHeadNameSnapshot ?? "Fee";
                if (due <= 0m)
                    return ConflictEnvelope($"{name} ({fee.Month}) pehle se paid hai.");
                if (line.Amount > due)
                    return BadRequestEnvelope($"{name} ({fee.Month}): amount baaqi Rs {due:N2} se zyada nahi ho sakta.");
            }

            decimal total = 0m;
            foreach (var line in lines)
            {
                var fee = byId[line.FeeId];
                var receipt = NewReceiptNo("PAY", fee.Id);
                _db.FeePayments.Add(new FeePayment
                {
                    FeeId = fee.Id,
                    Amount = line.Amount,
                    PaidDate = paidDate,
                    ReceiptNo = receipt,
                    Method = method,
                    Notes = notes,
                    CreatedAtUtc = DateTime.UtcNow
                });
                fee.AmountPaid += line.Amount;
                fee.ReceiptNo = receipt;
                ApplyStatus(fee, paidDate);
                total += line.Amount;
            }

            await _db.SaveChangesAsync(ct);
            await tx.CommitAsync(ct);

            var left = Math.Max(0m, balanceBefore - total);
            return OkEnvelope(new FeeCollectResult(total, left, lines.Count),
                $"Rs {total:N2} received for {lines.Count} fee(s). Remaining balance Rs {left:N2}.");
        });
    }
