using System.Globalization;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using SmartSchool.Core.DTOs;
using SmartSchool.Core.Interfaces;
using SmartSchool.Core.Models;
using SmartSchool.Infrastructure.Data; // <-- CHANGED: transaction ledger and payment history persistence.
using SmartSchool.Shared.Common;
using SmartSchool.Shared.Constants;
using SmartSchool.Shared.Enums;
using SmartSchool.Shared.Helpers;

namespace SmartSchool.API.Controllers;

[ApiController]
[Route("api/[controller]")]
public sealed class FeesController : BaseApiController
{
    private readonly IUnitOfWork _uow;
    private readonly SchoolDbContext _db; // <-- CHANGED: persist payment transactions with the fee balance.

    public FeesController(IUnitOfWork uow, SchoolDbContext db) { _uow = uow; _db = db; }

    private static string EffectiveStatus(FeeStatus status, DateOnly dueDate)
        => status == FeeStatus.Pending && dueDate < PkTime.TodayPk
            ? nameof(FeeStatus.Overdue)
            : status.ToString();

    private static FeeListItem ToDto(Fee f, decimal lastPaymentAmount = 0m) => new(
        f.Id, f.StudentId, f.Student.FullName,
        f.Student.Class.Name + "-" + f.Student.Class.Section,
        f.Amount, f.Month, f.DueDate, f.PaidDate,
        EffectiveStatus(f.Status, f.DueDate), f.ReceiptNo, f.Notes,
        f.AmountPaid, Math.Max(0m, f.Amount - f.AmountPaid), f.FeeHeadNameSnapshot, f.IsAutoGenerated, lastPaymentAmount);

    [HttpGet]
    [Authorize(Roles = AppRoles.StaffAndTeachers)]
    public async Task<ActionResult<ApiResponse<PagedResult<FeeListItem>>>> GetAll(
        [FromQuery] int? studentId,
        [FromQuery] string? month,
        [FromQuery] string? status,
        [FromQuery] int page = 1,
        [FromQuery] int pageSize = 20,
        CancellationToken ct = default)
    {
        page = Math.Max(1, page);
        pageSize = Math.Clamp(pageSize, 1, 200);

        var query = _uow.Fees.Query()
            .Include(f => f.Student).ThenInclude(s => s.Class)
            .AsQueryable();

        if (studentId is not null)
            query = query.Where(f => f.StudentId == studentId);
        if (!string.IsNullOrWhiteSpace(month))
            query = query.Where(f => f.Month == month);
        if (!string.IsNullOrWhiteSpace(status) && Enum.TryParse<FeeStatus>(status, true, out var parsed))
            query = query.Where(f => f.Status == parsed);

        var total = await query.CountAsync(ct);
        var rows = await query
            .OrderByDescending(f => f.DueDate).ThenByDescending(f => f.Id)
            .Skip((page - 1) * pageSize).Take(pageSize)
            .ToListAsync(ct);

        return OkEnvelope(PagedResult<FeeListItem>.Create(rows.Select(f => ToDto(f)).ToList(), page, pageSize, total));
    }

    /// <summary>Fees of one student - staff/teachers, or that student's parent.</summary>
    [HttpGet("student/{studentId:int}")]
    public async Task<ActionResult<ApiResponse<IReadOnlyList<FeeListItem>>>> GetByStudent(
        int studentId, CancellationToken ct)
    {
        if (IsParent)
        {
            var owns = await _uow.ParentStudents.AnyAsync(
                ps => ps.ParentUserId == CallerUserId && ps.StudentId == studentId, ct);
            if (!owns)
                return Forbid();
        }
        else if (!IsStaff && CallerRole != AppRoles.Teacher)
        {
            return Forbid();
        }

        var rows = await _uow.Fees.Query()
            .Include(f => f.Student).ThenInclude(s => s.Class)
            .Where(f => f.StudentId == studentId)
            .OrderByDescending(f => f.Month)
            .ToListAsync(ct);

        return OkEnvelope<IReadOnlyList<FeeListItem>>(rows.Select(f => ToDto(f)).ToList());
    }

    /// <summary>Everyone who still owes money (Pending + Partial + past-due), with totals.</summary>
    [HttpGet("dues")]
    [Authorize(Roles = AppRoles.StaffAndTeachers)]
    public async Task<ActionResult<ApiResponse<DuesSummaryResponse>>> GetDues(
        [FromQuery] int? classId,
        [FromQuery] string? month,
        CancellationToken ct = default)
    {
        var query = _uow.Fees.Query()
            .Include(f => f.Student).ThenInclude(s => s.Class)
            .Where(f => f.Status != FeeStatus.Paid);

        if (classId is not null)
            query = query.Where(f => f.Student.ClassId == classId);
        if (!string.IsNullOrWhiteSpace(month))
            query = query.Where(f => f.Month == month);

        var rows = await query.OrderBy(f => f.DueDate).Take(500).ToListAsync(ct);
        var items = rows.Select(f => ToDto(f)).ToList();

        return OkEnvelope(new DuesSummaryResponse(items.Count, items.Sum(i => i.Balance), items)); // <-- CHANGED: dues are remaining balance, not original invoice total.
    }

    /// <summary>
    /// Legacy rows marked 'Partial' by the old system (no stored paid amount) - the office must
    /// verify each amount before any further collection. Read-only; nothing is guessed.
    /// </summary>
    [HttpGet("legacy-partials")]
    [Authorize(Roles = AppRoles.Staff)]
    public async Task<ActionResult<ApiResponse<IReadOnlyList<FeeListItem>>>> GetLegacyPartials(CancellationToken ct)
    {
        var rows = await _uow.Fees.Query()
            .Include(f => f.Student).ThenInclude(s => s.Class)
            .Where(f => f.Status == FeeStatus.Partial && f.AmountPaid == 0m)
            .OrderBy(f => f.Student.FullName).ThenBy(f => f.Month)
            .ToListAsync(ct);
        return OkEnvelope<IReadOnlyList<FeeListItem>>(rows.Select(f => ToDto(f)).ToList());
    }

    [HttpPost]
    [Authorize(Roles = AppRoles.Staff)]
    public async Task<ActionResult<ApiResponse<FeeListItem>>> Create(FeeCreateRequest request, CancellationToken ct)
    {
        var student = await _uow.Students.Query(false).Include(s => s.Class)
            .FirstOrDefaultAsync(s => s.Id == request.StudentId, ct);
        if (student is null)
            return BadRequestEnvelope($"Student {request.StudentId} does not exist.");

        var fee = new Fee
        {
            StudentId = student.Id,
            Amount = request.Amount,
            Month = request.Month,
            DueDate = request.DueDate,
            Notes = request.Notes,
            Status = FeeStatus.Pending,
            CreatedAtUtc = DateTime.UtcNow
        };
        await _uow.Fees.AddAsync(fee, ct);
        await _uow.SaveChangesAsync(ct);

        fee.Student = student;
        return CreatedEnvelope(ToDto(fee), "Fee created successfully.");
    }

    [HttpPut("{id:int}")]
    [Authorize(Roles = AppRoles.Staff)]
    public async Task<ActionResult> Update(int id, FeeUpdateRequest request, CancellationToken ct)
    {
        var fee = await _uow.Fees.FindAsync(new object[] { id }, ct);
        if (fee is null)
            return NotFoundEnvelope($"Fee {id} was not found.");
        if (fee.Status == FeeStatus.Paid)
            return ConflictEnvelope("A paid fee cannot be edited.");
        if (fee.IsAutoGenerated)
            return ConflictEnvelope("Automatically generated fee snapshots cannot be edited; adjust the plan for future periods.");
        if (fee.AmountPaid > 0m)
            return ConflictEnvelope("A fee with payment history cannot be edited.");

        fee.Amount = request.Amount;
        fee.Month = request.Month;
        fee.DueDate = request.DueDate;
        fee.Notes = request.Notes;

        if (!string.IsNullOrWhiteSpace(request.Status)
            && Enum.TryParse<FeeStatus>(request.Status, true, out var status))
            fee.Status = status;

        await _uow.SaveChangesAsync(ct);
        return OkMessage("Fee updated successfully.");
    }

    [HttpDelete("{id:int}")]
    [Authorize(Roles = AppRoles.Staff)]
    public async Task<ActionResult> Delete(int id, CancellationToken ct)
    {
        var fee = await _uow.Fees.FindAsync(new object[] { id }, ct);
        if (fee is null)
            return NotFoundEnvelope($"Fee {id} was not found.");
        if (fee.Status == FeeStatus.Paid || fee.AmountPaid > 0m || await _db.FeePayments.AnyAsync(x => x.FeeId == fee.Id, ct))
            return ConflictEnvelope("A fee with payment history cannot be deleted (keep the audit trail).");
        if (fee.IsAutoGenerated)
            return ConflictEnvelope("Automatically generated fees cannot be deleted; deactivate the plan to stop future bills.");

        _uow.Fees.Remove(fee);
        await _uow.SaveChangesAsync(ct);
        return OkMessage("Fee deleted successfully.");
    }

    /// <summary>Mark a fee as paid; generates receipt INV-{yyyyMM}-{id:D6}.</summary>
    /// <summary>Parent app: every fee row of MY children (paid history + pending dues together).</summary>
    [HttpGet("my")]
    [Authorize(Roles = AppRoles.Parent)]
    public async Task<ActionResult<ApiResponse<IReadOnlyList<FeeListItem>>>> GetMine(CancellationToken ct)
    {
        var childIds = await _uow.ParentStudents.Query()
            .Where(ps => ps.ParentUserId == CallerUserId)
            .Select(ps => ps.StudentId)
            .ToListAsync(ct);

        var rows = await _uow.Fees.Query()
            .Include(f => f.Student).ThenInclude(s => s.Class)
            .Where(f => childIds.Contains(f.StudentId))
            .OrderBy(f => f.StudentId).ThenByDescending(f => f.Month)
            .ToListAsync(ct);

        return OkEnvelope((IReadOnlyList<FeeListItem>)rows.Select(f => ToDto(f)).ToList());
    }

    /// <summary>Parent app: receipt data for ONE of my children's PAID fees (PDF rendered client-side).</summary>
    [HttpGet("my/{id:int}/receipt")]
    [Authorize(Roles = AppRoles.Parent)]
    public async Task<ActionResult<ApiResponse<FeeReceiptDto>>> GetMyReceipt(int id, CancellationToken ct)
    {
        var fee = await _uow.Fees.Query()
            .Include(f => f.Student).ThenInclude(s => s.Class)
            .FirstOrDefaultAsync(f => f.Id == id, ct);
        if (fee is null)
            return NotFoundEnvelope($"Fee receipt {id} was not found.");

        var owns = await _uow.ParentStudents.Query()
            .AnyAsync(ps => ps.ParentUserId == CallerUserId && ps.StudentId == fee.StudentId, ct);
        if (!owns)
            return Forbid();

        if (fee.Status != FeeStatus.Paid || fee.PaidDate is null || fee.ReceiptNo is null)
            return BadRequestEnvelope("This fee is not paid yet - no receipt exists.");

        var receipt = new FeeReceiptDto(
            fee.ReceiptNo, fee.Student.FullName,
            fee.Student.Class.Name + "-" + fee.Student.Class.Section,
            fee.Month, fee.Amount, fee.DueDate, fee.PaidDate.Value,
            fee.PaidDate.Value.ToString("dd MMM yyyy", CultureInfo.InvariantCulture),
            fee.Notes);

        return OkEnvelope(receipt);
    }

    [HttpGet("{id:int}/payments")]
    [Authorize]
    public async Task<ActionResult<ApiResponse<IReadOnlyList<FeePaymentItem>>>> GetPaymentHistory(int id, CancellationToken ct)
    {
        var fee = await _db.Fees.AsNoTracking().Include(f => f.Student).FirstOrDefaultAsync(f => f.Id == id, ct);
        if (fee is null) return NotFoundEnvelope($"Fee {id} was not found.");
        if (IsParent)
        {
            if (!await _db.ParentStudents.AnyAsync(x => x.ParentUserId == CallerUserId && x.StudentId == fee.StudentId, ct)) return Forbid();
        }
        else if (!IsStaff) return Forbid();
        var items = await _db.FeePayments.AsNoTracking().Where(x => x.FeeId == id).OrderBy(x => x.PaidDate).ThenBy(x => x.Id)
            .Select(x => new FeePaymentItem(x.Id, x.FeeId, x.Amount, x.PaidDate, x.ReceiptNo, x.Method, x.Notes)).ToListAsync(ct);
        return OkEnvelope<IReadOnlyList<FeePaymentItem>>(items);
    }

    [HttpPost("{id:int}/pay")]
    [Authorize(Roles = AppRoles.Staff)]
    public async Task<ActionResult<ApiResponse<FeeListItem>>> Pay(int id, PayFeeRequest? request, CancellationToken ct)
    {
        // The app uses EnableRetryOnFailure, so user-initiated transactions must run inside
        // the execution strategy (otherwise EF throws at runtime).
        var strategy = _db.Database.CreateExecutionStrategy();
        return await strategy.ExecuteAsync<ActionResult<ApiResponse<FeeListItem>>>(async () =>
        {
            await using var transaction = await _db.Database.BeginTransactionAsync(System.Data.IsolationLevel.Serializable, ct);
            var fee = await _db.Fees.Include(f => f.Student).ThenInclude(s => s.Class).FirstOrDefaultAsync(f => f.Id == id, ct);
            if (fee is null) return NotFoundEnvelope($"Fee {id} was not found.");
            var balance = Math.Max(0m, fee.Amount - fee.AmountPaid);
            if (balance <= 0m) return ConflictEnvelope($"Fee {id} is already fully paid.");
            var amount = request?.Amount ?? balance;
            if (amount <= 0m || amount > balance)
                return BadRequestEnvelope($"Payment must be greater than zero and no more than the remaining balance Rs {balance:N2}.");

            var paidDate = request?.PaidDate ?? PkTime.TodayPk;
            var payment = new FeePayment
            {
                FeeId = fee.Id,
                Amount = amount,
                PaidDate = paidDate,
                ReceiptNo = $"PAY-{fee.Id:D6}-{Guid.NewGuid():N}"[..23].ToUpperInvariant(),
                Method = string.IsNullOrWhiteSpace(request?.Method) ? "Cash" : request.Method.Trim(),
                Notes = request?.Notes,
                CreatedAtUtc = DateTime.UtcNow
            };
            _db.FeePayments.Add(payment);
            fee.AmountPaid += amount;
            fee.Status = fee.AmountPaid >= fee.Amount ? FeeStatus.Paid : FeeStatus.Partial;
            fee.PaidDate = fee.Status == FeeStatus.Paid ? paidDate : null;
            fee.ReceiptNo = payment.ReceiptNo;
            await _db.SaveChangesAsync(ct);
            await transaction.CommitAsync(ct);
            return OkEnvelope(ToDto(fee, amount), $"Payment Rs {amount:N2} recorded. Remaining balance Rs {Math.Max(0m, fee.Amount - fee.AmountPaid):N2}; receipt {payment.ReceiptNo}.");
        });
    }
}
